<?php

declare(strict_types=1);

namespace Infrastructure\Persistence;

use LogicException;
use PDO;
use RuntimeException;
use Throwable;

/** Bounded operator conversion; original storage is read-only and target acceptance is atomic. */
final class PostgresDatabaseConverter
{
    public string $phase = 'inspect';
    public ?string $table = null;

    public function __construct(private PDO $source, private PDO $target)
    {
        if (
            $source->getAttribute(PDO::ATTR_DRIVER_NAME) !== 'mysql' ||
            $target->getAttribute(PDO::ATTR_DRIVER_NAME) !== 'pgsql'
        ) {
            throw new LogicException('Use an explicit MariaDB source and PostgreSQL target.');
        }
    }

    private function quote(string $name): string
    {
        if (!preg_match('/^[a-z][a-z0-9_]*$/D', $name)) {
            throw new LogicException('Review an unsupported database identifier.');
        }
        return '"' . $name . '"';
    }

    private function name(string $table, string $name): string
    {
        return strtolower(substr($table . '_' . $name, 0, 46)) . '_' .
        substr(hash('sha256', $table . ':' . $name), 0, 12);
    }

    private function metadata(): array
    {
        $tables = $this->source->query('SELECT TABLE_NAME, TABLE_TYPE, AUTO_INCREMENT '
            . 'FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() ORDER BY TABLE_NAME')
            ->fetchAll(PDO::FETCH_ASSOC);
        if (count($tables) > 300) {
            throw new LogicException('This conversion exceeds its table allowance.');
        }
        $result = [];
        foreach ($tables as $table) {
            $name = $table['TABLE_NAME'];
            $this->quote($name);
            if ($table['TABLE_TYPE'] !== 'BASE TABLE') {
                throw new LogicException('Views require explicit conversion.');
            }
            $result[$name] = [
                'columns' => $this->source->query('SHOW FULL COLUMNS FROM `' . $name . '`')->fetchAll(PDO::FETCH_ASSOC),
                'indexes' => $this->source->query('SHOW INDEX FROM `' . $name . '`')->fetchAll(PDO::FETCH_ASSOC),
                'ddl' => $this->source->query('SHOW CREATE TABLE `' . $name . '`')->fetch(PDO::FETCH_NUM)[1],
                'next_identity' => $table['AUTO_INCREMENT'],
            ];
        }
        return $result;
    }

    private function column(array $column): string
    {
        $type = strtolower($column['Type']);
        $unsigned = str_contains($type, 'unsigned');
        $mapped = match (true) {
            str_starts_with($type, 'bigint') => $unsigned ? 'numeric(20)' : 'bigint',
            str_starts_with($type, 'tinyint') => 'smallint',
            preg_match('/^int(?:\(| |$)/', $type) === 1 => $unsigned ? 'bigint' : 'integer',
            preg_match('/^varchar\(([0-9]+)\)$/D', $type, $match) === 1 => 'varchar(' . $match[1] . ')',
            in_array($type, ['text', 'mediumtext', 'longtext'], true) => 'text',
            $type === 'date' => 'date',
            preg_match('/^datetime(?:\(([0-6])\))?$/D', $type, $match) === 1 =>
            'timestamp(' . ($match[1] ?? '0') . ') without time zone',
            default => throw new LogicException('Review an unsupported column type.'),
        };
        $sql = $this->quote($column['Field']) . ' ' . $mapped;
        if ($column['Collation'] !== null) {
            if ($column['Collation'] !== 'utf8mb4_unicode_ci') {
                throw new LogicException('Review an unsupported source collation.');
            }
            $sql .= ' COLLATE public.etsis_unicode_ci';
        }
        $extra = strtolower($column['Extra']);
        if ($extra === 'auto_increment') {
            $sql .= ' GENERATED BY DEFAULT AS IDENTITY';
        } elseif ($extra !== '') {
            throw new LogicException('Review a generated or automatically updated column.');
        } elseif ($column['Default'] !== null) {
            $value = (string) $column['Default'];
            $literal = str_starts_with($value, "'") && str_ends_with($value, "'");
            if ($literal) {
                $value = strtr(substr($value, 1, -1), ["''" => "'", "\\'" => "'", "\\\\" => "\\"]);
            }
            $sql .= ' DEFAULT ' . (!$literal && str_starts_with($type, 'datetime') &&
                preg_match('/^current_timestamp(?:\(\))?$/iD', $value)
                ? 'CURRENT_TIMESTAMP' : $this->target->quote($value));
        }
        if ($column['Null'] === 'NO') {
            $sql .= ' NOT NULL';
        }
        if ($unsigned) {
            $sql .= ' CHECK (' . $this->quote($column['Field']) . ' >= 0)';
        }
        return $sql;
    }

    private function fingerprint(PDO $pdo, string $table, array $columns, ?array &$backup = null): array
    {
        $query = $pdo->query('SELECT ' . implode(', ', array_map(
            $pdo === $this->source ? static fn (string $c): string => '`' . $c . '`' : $this->quote(...),
            $columns
        )) . ' FROM ' . ($pdo === $this->source ? '`' . $table . '`' : $this->quote($table)));
        $hashes = [];
        $bytes = 0;
        while (($row = $query->fetch(PDO::FETCH_ASSOC)) !== false) {
            $canonical = json_encode(array_map(
                static fn (mixed $v): ?string => $v === null ? null : (string) $v,
                $row
            ), JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE);
            $bytes += strlen($canonical);
            if (count($hashes) >= 10000 || $bytes > 8_388_608) {
                throw new LogicException('This conversion exceeds its row/byte allowance.');
            }
            $hashes[] = hash('sha256', $canonical);
            if ($backup !== null) {
                $backup[] = $row;
            }
        }
        sort($hashes, SORT_STRING);
        return ['rows' => count($hashes), 'digest' => hash('sha256', implode('', $hashes)), 'bytes' => $bytes];
    }

    /** Returns protected backup material to the operator, never an ordinary application response. */
    public function copy(): array
    {
        if (
            (int) $this->target->query("SELECT COUNT(*) FROM information_schema.tables " .
            "WHERE table_schema = 'public'")->fetchColumn() !== 0
        ) {
            throw new LogicException('Use an empty target database.');
        }
        $this->source->exec('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ');
        $this->source->exec('START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY');
        $this->target->beginTransaction();
        try {
            $meta = $this->metadata();
            $this->target->exec("CREATE COLLATION public.etsis_unicode_ci " .
                "(provider=icu, locale='und-u-ks-level1', deterministic=false)");
            $backup = $manifest = [];
            $total = $totalBytes = 0;
            foreach ($meta as $name => $definition) {
                $this->table = $name;
                $this->phase = 'schema';
                $fields = array_column($definition['columns'], 'Field');
                $this->target->exec('CREATE TABLE ' . $this->quote($name) . ' (' .
                    implode(', ', array_map($this->column(...), $definition['columns'])) . ')');
                $rows = [];
                $manifest[$name] = $this->fingerprint($this->source, $name, $fields, $rows);
                $total += count($rows);
                $totalBytes += $manifest[$name]['bytes'];
                if ($total > 10000 || $totalBytes > 8_388_608) {
                    throw new LogicException('This conversion exceeds its total allowance.');
                }
                $this->phase = 'copy';
                $insert = $this->target->prepare('INSERT INTO ' . $this->quote($name) . ' (' .
                    implode(', ', array_map($this->quote(...), $fields)) . ') VALUES (' .
                    implode(', ', array_fill(0, count($fields), '?')) . ')');
                foreach ($rows as $row) {
                    $insert->execute(array_values($row));
                }
                $backup[$name] = ['ddl' => $definition['ddl'], 'rows' => $rows];
            }
            $this->phase = 'indexes';
            foreach ($meta as $name => $definition) {
                $this->table = $name;
                $indexes = [];
                foreach ($definition['indexes'] as $index) {
                    if ($index['Index_type'] !== 'BTREE' || $index['Sub_part'] !== null) {
                        throw new LogicException('Review an unsupported index.');
                    }
                    $indexes[$index['Key_name']][] = $index;
                }
                foreach ($indexes as $key => $parts) {
                    usort($parts, static fn (array $a, array $b): int => $a['Seq_in_index'] <=> $b['Seq_in_index']);
                    $columns = implode(', ', array_map(fn (array $p): string => $this->quote($p['Column_name']) .
                        ($p['Collation'] === 'D' ? ' DESC' : ''), $parts));
                    if ($key === 'PRIMARY') {
                        $this->target->exec(
                            'ALTER TABLE ' . $this->quote($name) . ' ADD PRIMARY KEY (' . $columns . ')'
                        );
                    } else {
                        $this->target->exec('CREATE ' . ((int) $parts[0]['Non_unique'] === 0 ? 'UNIQUE ' : '') .
                            'INDEX ' . $this->quote($this->name($name, $key)) . ' ON ' . $this->quote($name) .
                            ' (' . $columns . ')');
                    }
                }
                foreach ($definition['columns'] as $column) {
                    if ($column['Extra'] === 'auto_increment') {
                        $sequence = $this->target->prepare('SELECT pg_get_serial_sequence(?, ?)');
                        $sequence->execute([$name, $column['Field']]);
                        $set = $this->target->prepare('SELECT setval(CAST(? AS regclass), ?, false)');
                        $set->execute([$sequence->fetchColumn(), max(1, (int) $definition['next_identity'])]);
                    }
                }
            }
            $this->phase = 'relationships';
            $foreign = $this->source->query('SELECT k.TABLE_NAME,k.CONSTRAINT_NAME,k.COLUMN_NAME,'
                . 'k.REFERENCED_TABLE_NAME,k.REFERENCED_COLUMN_NAME,k.ORDINAL_POSITION,r.UPDATE_RULE,r.DELETE_RULE '
                . 'FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r '
                . 'ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME '
                . 'AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME WHERE k.TABLE_SCHEMA=DATABASE() '
                . 'AND k.REFERENCED_TABLE_NAME IS NOT NULL ORDER BY k.TABLE_NAME,k.CONSTRAINT_NAME,k.ORDINAL_POSITION')
                ->fetchAll(PDO::FETCH_ASSOC);
            $keys = [];
            $foreignCount = 0;
            foreach ($foreign as $key) {
                $keys[$key['TABLE_NAME']][$key['CONSTRAINT_NAME']][] = $key;
            }
            foreach ($keys as $table => $constraints) {
                $this->table = $table;
                foreach ($constraints as $name => $parts) {
                    $foreignCount++;
                    $first = $parts[0];
                    foreach (['UPDATE_RULE', 'DELETE_RULE'] as $rule) {
                        if (!in_array($first[$rule], ['CASCADE', 'RESTRICT', 'NO ACTION', 'SET NULL'], true)) {
                            throw new LogicException('Review an unsupported referential action.');
                        }
                    }
                    $this->target->exec('ALTER TABLE ' . $this->quote($table) . ' ADD CONSTRAINT ' .
                        $this->quote($this->name($table, $name)) . ' FOREIGN KEY (' . implode(
                            ', ',
                            array_map($this->quote(...), array_column($parts, 'COLUMN_NAME'))
                        ) . ') REFERENCES ' .
                        $this->quote($first['REFERENCED_TABLE_NAME']) . ' (' . implode(
                            ', ',
                            array_map($this->quote(...), array_column($parts, 'REFERENCED_COLUMN_NAME'))
                        ) .
                        ') ON UPDATE ' . $first['UPDATE_RULE'] . ' ON DELETE ' . $first['DELETE_RULE']);
                }
            }
            $this->phase = 'verify';
            foreach ($meta as $name => $definition) {
                $this->table = $name;
                if (
                    $this->fingerprint($this->target, $name, array_column($definition['columns'], 'Field')) !==
                    $manifest[$name]
                ) {
                    throw new RuntimeException('The target does not exactly match the source.');
                }
            }
            $this->target->commit();
            $this->source->rollBack();
            $this->phase = 'complete';
            return ['tables' => count($meta), 'rows' => $total, 'foreign_keys' => $foreignCount,
                'manifest' => $manifest, 'backup' => $backup];
        } catch (Throwable $error) {
            if ($this->target->inTransaction()) {
                $this->target->rollBack();
            }
            if ($this->source->inTransaction()) {
                $this->source->rollBack();
            }
            throw $error;
        }
    }

    public function __debugInfo(): array
    {
        return ['conversion' => '[protected operator operation]', 'phase' => $this->phase];
    }
}
